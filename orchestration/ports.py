"""Infrastructure boundaries used by application orchestration."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Protocol

from .models import Assignment, Outcome


class DeviceLease(Protocol):
    fd: int | None

    def close(self) -> None: ...


@dataclass(frozen=True)
class PreparedEnvironment:
    """An allocated environment may acquire a new transport address on each run."""

    device: str
    instance_id: str = ""
    lease: DeviceLease | None = None
    tunnel_pid: int | None = None


class ProcessExecutor(Protocol):
    def run(self, command: list[str], output: Path, *, lock_fd: int | tuple[int, ...],
            check: Callable[[], None], on_start: Callable[[int], None]) -> int: ...


class TaskExecutor(Protocol):
    def execute(self, assignment: Assignment, device_lock: DeviceLease) -> Outcome: ...


class EnvironmentManager(Protocol):
    def prepare(self, assignment: Assignment, deadline: float, check: Callable[[], None]) -> PreparedEnvironment: ...
    def reset(self, serial: str, package: str, policy: str) -> bool | None: ...


class WorkerRepository(Protocol):
    def touch(self, assignment: Assignment, *, state: str | None = None, pid: int | None = None) -> None: ...
    def is_cancelled(self, task_id: str) -> bool: ...
    def finish(self, assignment: Assignment, outcome: Outcome, environment_error: str = "") -> None: ...


class SchedulerRepository(WorkerRepository, Protocol):
    path: Path

    def snapshot(self) -> dict: ...
    def claim(self, serial: str, owner: str, output_root: Path) -> Assignment | None: ...
    def quarantine(self, serial: str, error: str) -> None: ...
    def recover_interrupted(self) -> int: ...


class CloudResourceRepository(Protocol):
    def begin_cloud_resource(self, assignment: Assignment, timeout_seconds: int) -> dict: ...
    def update_cloud_resource(self, attempt_id: str, **changes: object) -> None: ...
    def cloud_resources(self, *, pending_only: bool = True) -> list[dict]: ...
    def recover_environment(self, serial: str) -> None: ...
    def quarantine(self, serial: str, error: str) -> None: ...


class SandboxProvider(Protocol):
    """Cloud control plane and local ADB tunnel adapter. No task scheduling here."""

    def create(self, resource: dict, deadline: float, check: Callable[[], None]) -> str: ...
    def state(self, instance_id: str, region: str, deadline: float, check: Callable[[], None]) -> str: ...
    def connect(self, instance_id: str, region: str, deadline: float, check: Callable[[], None]) -> PreparedEnvironment: ...
    def disconnect(self, instance_id: str, region: str, deadline: float) -> None: ...
    def delete(self, instance_id: str, region: str, deadline: float) -> None: ...
    def find(self, resource: dict, deadline: float) -> list[str]: ...
